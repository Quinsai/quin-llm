"""Generate controlled SFT configs from the baseline step budget.

The baseline and mixed runs must use the same ``max_steps`` and both must
disable early stopping; otherwise the comparison confounds "teacher data" with
"more optimizer steps".  This command reads ``baseline_budget.json`` written by
``distillation.preflight`` and emits ready-to-run YAML files.

Example:
    python -m distillation.make_configs \
        --budget data/distill/baseline_budget.json \
        --run-id distill_v1 \
        --mixed-data data/distill/sft/distill_v1/train.parquet
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
from typing import Any

import yaml

from config import load_yaml


def _write(path: Path, cfg: dict[str, Any], header: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True)
    path.write_text(header + "\n" + text, encoding="utf-8")
    print(f"wrote {path}")


def _base_config(path: str) -> dict[str, Any]:
    cfg = load_yaml(path)
    if "data" not in cfg or "train" not in cfg:
        raise ValueError(f"{path} is not an SFT config (missing data/train)")
    return copy.deepcopy(cfg)


def _controlled(
    base: dict[str, Any],
    *,
    data_out: str,
    train_out: str,
    source: dict[str, Any],
    max_steps: int,
) -> dict[str, Any]:
    cfg = copy.deepcopy(base)
    cfg["data"]["out_dir"] = data_out
    cfg["data"]["source"] = source
    cfg["train"]["out_dir"] = train_out
    cfg["train"]["max_steps"] = int(max_steps)
    cfg["train"]["epochs"] = None
    cfg["train"]["early_stop_patience"] = None
    return cfg


def run_make_configs(
    *,
    budget_path: str,
    base_path: str,
    out_dir: str,
    run_id: str,
    mixed_data: str,
    alpaca_control: str | None = None,
    max_steps: int | None = None,
) -> list[Path]:
    budget_file = Path(budget_path)
    if max_steps is None:
        if not budget_file.exists():
            raise FileNotFoundError(
                f"{budget_file} not found; run `python -m distillation.preflight` first"
            )
        budget = json.loads(budget_file.read_text(encoding="utf-8"))
        max_steps = int(budget.get("max_steps") or 0)
    if max_steps <= 0:
        raise ValueError("max_steps must be positive")

    base = _base_config(base_path)
    out = Path(out_dir)
    header = (
        f"# Generated by distillation.make_configs from {budget_path}.\n"
        f"# run_id={run_id}  max_steps={max_steps}  "
        "early_stop_patience=null (controlled comparison)."
    )

    baseline = _controlled(
        base,
        data_out=f"processed_data/sft_baseline_{run_id}",
        train_out=f"checkpoints/sft_baseline_{run_id}",
        source={
            "type": "alpaca",
            "paths": "data/raw/alpaca/*.parquet",
            "split": "train",
        },
        max_steps=max_steps,
    )
    mixed = _controlled(
        base,
        data_out=f"processed_data/sft_distill_{run_id}",
        train_out=f"checkpoints/sft_distill_{run_id}",
        source={
            "type": "alpaca",
            "paths": mixed_data,
            "split": "train",
        },
        max_steps=max_steps,
    )

    paths = []
    p = out / f"sft_baseline_{run_id}.yaml"
    _write(p, baseline, header)
    paths.append(p)
    p = out / f"sft_distill_{run_id}.yaml"
    _write(p, mixed, header)
    paths.append(p)

    if alpaca_control:
        control = _controlled(
            base,
            data_out=f"processed_data/sft_alpaca_control_{run_id}",
            train_out=f"checkpoints/sft_alpaca_control_{run_id}",
            source={
                "type": "alpaca",
                "paths": alpaca_control,
                "split": "train",
            },
            max_steps=max_steps,
        )
        p = out / f"sft_alpaca_control_{run_id}.yaml"
        _write(p, control, header)
        paths.append(p)

    print(
        "\nnext:\n"
        f"  python main.py prepare-sft --config {paths[0]} "
        "--ckpt checkpoints/pretrain_full/best.pt\n"
        f"  python main.py sft --config {paths[0]} "
        "--ckpt checkpoints/pretrain_full/best.pt\n"
        f"  python main.py prepare-sft --config {paths[1]} "
        "--ckpt checkpoints/pretrain_full/best.pt\n"
        f"  python main.py sft --config {paths[1]} "
        "--ckpt checkpoints/pretrain_full/best.pt"
    )
    return paths


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate controlled SFT YAMLs")
    parser.add_argument("--budget", default="data/distill/baseline_budget.json")
    parser.add_argument("--base", default="configs/sft_full.yaml")
    parser.add_argument("--out-dir", default="configs/generated")
    parser.add_argument("--run-id", default="distill_v1")
    parser.add_argument(
        "--mixed-data", default="data/distill/sft/distill_v1/train.parquet"
    )
    parser.add_argument("--alpaca-control", default=None)
    parser.add_argument("--max-steps", type=int, default=None)
    args = parser.parse_args()

    run_make_configs(
        budget_path=args.budget,
        base_path=args.base,
        out_dir=args.out_dir,
        run_id=args.run_id,
        mixed_data=args.mixed_data,
        alpaca_control=args.alpaca_control,
        max_steps=args.max_steps,
    )


if __name__ == "__main__":
    main()
